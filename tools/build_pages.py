def build(slug, p):
    html = TEMPLATE
    html = html.replace('data-exercise="leg-press"', f'data-exercise="{slug}"')
    html = re.sub(r"<title>.*?</title>", f"<title>{p['title']} — Рычаг</title>", html)
    html = re.sub(r'<meta name="description" content=".*?">', f'<meta name="description" content="{p["desc"]}">', html)
    html = re.sub(r'<p class="eyebrow">.*?</p>', f'<p class="eyebrow">{p["eyebrow"]}</p>', html)
    html = re.sub(r"<h1>.*?</h1>", f"<h1>{p['title']}</h1>", html)
    html = re.sub(r'<p class="lead">.*?</p>', f'<p class="lead">{p["lead"]}</p>', html)
    html = re.sub(r'(<svg id="scene" role="group" aria-label=").*?(")', rf'\g<1>{p["aria"]}\g<2>', html)
    html = re.sub(
        r'(<summary>Как это считается</summary>\s*<div class="body">).*?(\s*</div>\s*</details>)',
        lambda m: m.group(1) + p["explain"] + m.group(2), html, count=1, flags=re.S)
    html = html.replace('assets/js/leg-press.js', f'assets/js/{slug}.js')
    (ROOT / "exercises" / f"{slug}.html").write_text(html, encoding="utf-8")
    print("ok", slug)


if __name__ == "__main__":
    import sys
    only = sys.argv[1:]
    for slug, p in PAGES.items():
        if not only or slug in only:
            build(slug, p)
